function assertBank() {
  const ids = new Set<string>();
  for (const question of QUESTIONS) {
    if (ids.has(question.id)) throw new Error(`Duplicate Magnitude question: ${question.id}`);
    ids.add(question.id);
    if (!question.prompt || !question.explanation || !question.source) {
      throw new Error(`Incomplete Magnitude question: ${question.id}`);
    }
    if (!Number.isFinite(question.answer) || question.min >= question.max) {
      throw new Error(`Bad range on Magnitude question: ${question.id}`);
    }
    if (question.scale === 'log' && (question.answer <= 0 || question.min <= 0)) {
      throw new Error(`Non-positive log range on Magnitude question: ${question.id}`);
    }
    if (question.answer < question.min || question.answer > question.max) {
      throw new Error(`Answer outside slider range: ${question.id}`);
    }
  }
  if (QUESTIONS.length < 60) {
    throw new Error(`Magnitude bank too small: ${QUESTIONS.length}`);
  }
}

