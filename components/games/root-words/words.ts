function assembliesThatSpell(word: string, forms: string[]): number {
  let count = 0;
  const walk = (used: boolean[], built: string) => {
    if (built === word) {
      count += 1;
      return;
    }
    if (built.length >= word.length || !word.startsWith(built)) return;
    for (let i = 0; i < forms.length; i += 1) {
      if (used[i]) continue;
      used[i] = true;
      walk(used, built + forms[i]);
      used[i] = false;
    }
  };
  walk(forms.map(() => false), '');
  return count;
}

function assertBank() {
  const ids = new Set<string>();
  const words = new Set<string>();
  for (const puzzle of WORDS) {
    if (ids.has(puzzle.id)) throw new Error(`Duplicate Root Words id: ${puzzle.id}`);
    ids.add(puzzle.id);
    if (words.has(puzzle.word)) throw new Error(`Duplicate Root Words word: ${puzzle.word}`);
    words.add(puzzle.word);
    if (!/^[a-z]+$/.test(puzzle.word)) throw new Error(`Bad word spelling: ${puzzle.id}`);
    if (!puzzle.prompt.includes('+')) throw new Error(`Prompt needs + : ${puzzle.id}`);
    if (!puzzle.note || puzzle.note.length < 40) throw new Error(`Short note: ${puzzle.id}`);
    if (!puzzle.source) throw new Error(`Missing source: ${puzzle.id}`);
    if (puzzle.roots.length < 2 || puzzle.roots.length > 4) {
      throw new Error(`Root count on ${puzzle.id}`);
    }
    if (puzzle.decoys.length < 3 || puzzle.decoys.length > 6) {
      throw new Error(`Decoy count on ${puzzle.id}`);
    }
    const joined = puzzle.roots.map((root) => root.form).join('');
    if (joined !== puzzle.word) {
      throw new Error(`${puzzle.id} roots join to "${joined}", not "${puzzle.word}"`);
    }
    const forms = [...puzzle.roots.map((root) => root.form), ...puzzle.decoys];
    if (forms.some((form) => !/^[a-z]+$/.test(form))) {
      throw new Error(`Non-letter tile on ${puzzle.id}`);
    }
    const unique = new Set(forms);
    if (unique.size !== forms.length) throw new Error(`Duplicate tile on ${puzzle.id}`);
    const ways = assembliesThatSpell(puzzle.word, forms);
    if (ways !== 1) throw new Error(`${puzzle.id} has ${ways} tile spellings`);
    const promptGlosses = puzzle.prompt.split('+').map((part) => part.trim());
    if (promptGlosses.length !== puzzle.roots.length) {
      throw new Error(`Prompt/root mismatch on ${puzzle.id}`);
    }
  }
  if (WORDS.length < 60) throw new Error(`Root Words bank too small: ${WORDS.length}`);
}

assertBank();
