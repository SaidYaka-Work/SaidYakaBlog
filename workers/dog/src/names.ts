export const DOG_NAMES: DogName[] = LABELS.map((label) => ({ id: slug(label), label }));

const BY_ID = new Map(DOG_NAMES.map((name) => [name.id, name]));

export function nameById(id: string) {
  return BY_ID.get(id) ?? null;
}

export function recentNameIds(names: Array<{ id?: string; name?: string }>, limit = 24) {
  const ids: string[] = [];
  for (const item of names) {
    if (item.id && BY_ID.has(item.id)) ids.push(item.id);
    else if (item.name) {
      const label = item.name;
      const found = DOG_NAMES.find((entry) => entry.label.toLowerCase() === label.toLowerCase());
      if (found) ids.push(found.id);
    }
  }
  return ids.slice(0, limit);
}

export function pickName(rng: () => number, avoidIds: string[] = []) {
  const avoid = new Set(avoidIds);
  const pool = DOG_NAMES.filter((name) => !avoid.has(name.id));
  const source = pool.length ? pool : DOG_NAMES;
  return source[Math.floor(rng() * source.length)] ?? DOG_NAMES[0];
}

export function suggestNames(rng: () => number, count = 5, avoidIds: string[] = []) {
  const picks: DogName[] = [];
  const avoid = avoidIds.slice();
  let guard = 0;
  while (picks.length < count && guard < 400) {
    guard += 1;
    const next = pickName(rng, avoid);
    if (picks.some((item) => item.id === next.id)) continue;
    picks.push(next);
    avoid.push(next.id);
  }
  return picks;
}
